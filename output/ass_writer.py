"""Assemble subtitle blocks into an Advanced SubStation Alpha (.ass) file.

ASS is Aegisub's native format: overlapping lines (an S block's stacked
lines, or N and S on screen together) stay separate lines. SRT can't
represent that, so Aegisub flattens/merges such lines when it handles an
.srt.

The script resolution (PlayResX/PlayResY) is the video's own size, so
override tags like \\pos are in that video's pixel coordinates. Every line
uses one plain "Default" style, meant to be restyled in Aegisub.
"""

# Aegisub's own default style is Arial 20 on a 640x480 script; the font
# size is scaled to the script height so text looks the same at any size.
_BASE_FONT_SIZE = 20
_BASE_HEIGHT = 480

_STYLE_FORMAT = (
    "Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
    "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, "
    "Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, "
    "MarginV, Encoding"
)
_EVENT_FORMAT = "Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"


def format_timestamp(seconds):
    """Convert a time in seconds to ASS format: H:MM:SS.cc (centiseconds)."""
    if seconds < 0:
        seconds = 0.0

    total_cs = int(round(seconds * 100))
    hours, total_cs = divmod(total_cs, 3600 * 100)
    minutes, total_cs = divmod(total_cs, 60 * 100)
    secs, centis = divmod(total_cs, 100)
    return f"{hours}:{minutes:02d}:{secs:02d}.{centis:02d}"


def write_ass(blocks, output_path, resolution=(1920, 1080)):
    """Write subtitle blocks to an .ass file.

    Args:
        blocks: Iterable of objects with `.start`, `.end` (seconds) and
            `.text` attributes, in time order.
        output_path: Destination path for the .ass file.
        resolution: (width, height) of the script — the video's size.
    """
    width, height = resolution
    font_size = max(1, round(_BASE_FONT_SIZE * height / _BASE_HEIGHT))
    with open(output_path, "w", encoding="utf-8-sig") as f:
        f.write("[Script Info]\n")
        f.write("; Script generated by Subtitle Timer\n")
        f.write("ScriptType: v4.00+\n")
        f.write(f"PlayResX: {width}\n")
        f.write(f"PlayResY: {height}\n")
        f.write("WrapStyle: 0\n")
        f.write("ScaledBorderAndShadow: yes\n")
        f.write("\n")
        f.write("[V4+ Styles]\n")
        f.write(f"Format: {_STYLE_FORMAT}\n")
        f.write(
            f"Style: Default,Arial,{font_size},&H00FFFFFF,&H000000FF,"
            "&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,2,2,10,10,10,1\n"
        )
        f.write("\n")
        f.write("[Events]\n")
        f.write(f"Format: {_EVENT_FORMAT}\n")
        for block in blocks:
            start = format_timestamp(block.start)
            end = format_timestamp(block.end)
            f.write(f"Dialogue: 0,{start},{end},Default,,0,0,0,,{block.text}\n")
